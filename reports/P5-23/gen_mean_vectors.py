"""Reference vectors for the exact group mean of P5-23 (D9, V2-44).

Python's float(Fraction) rounds a rational to the nearest binary64 with ties to even,
so sum(Fraction(x))/n converted to float is the canonical mean. Fixed seed, no I/O
except writing the Rust test table given on the command line.

Usage: python reports/P5-23/gen_mean_vectors.py core/crates/core-kernel/src/law/tests/mean_vectors.rs
"""

from __future__ import annotations

import random
import struct
import sys
from fractions import Fraction

SEED = 20261021


def bits(x: float) -> int:
    (value,) = struct.unpack("<Q", struct.pack("<d", x))
    return int(value)


def from_bits(b: int) -> float:
    (value,) = struct.unpack("<d", struct.pack("<Q", b))
    return float(value)


def canonical_mean(xs: list[float]) -> float:
    m = float(sum(map(Fraction, xs)) / len(xs))
    return 0.0 if m == 0 else m


def cases(rng: random.Random) -> list[list[float]]:
    out: list[list[float]] = []
    for _ in range(150):
        out.append([rng.uniform(-2, 2) for _ in range(rng.randint(1, 12))])
    for _ in range(40):  # differences a − b as the law computes them
        out.append([rng.uniform(-1, 1) - rng.uniform(-1, 1) for _ in range(rng.randint(1, 9))])
    for _ in range(30):  # tiny and subnormal magnitudes
        out.append([rng.choice((1, -1)) * from_bits(rng.randint(1, 1 << 54)) for _ in range(rng.randint(1, 6))])
    for _ in range(30):  # near ties: neighbours of 1.0 and 0.5
        base = rng.choice((1.0, 0.5, -0.25))
        out.append([from_bits(bits(base) + rng.randint(-3, 3)) for _ in range(rng.randint(2, 4))])
    for _ in range(20):  # cancellation to small results
        x = rng.uniform(-2, 2)
        out.append([x, -x, rng.uniform(-1e-12, 1e-12)])
    for _ in range(10):  # many members
        out.append([rng.uniform(-2, 2) for _ in range(rng.randint(200, 900))])
    out.append([2.0, 2.0, 2.0])
    out.append([-2.0, 2.0])
    out.append([4.0, -4.0, 4.0])
    return out


def main() -> int:
    rng = random.Random(SEED)
    rows = []
    for xs in cases(rng):
        ins = ", ".join(f"0x{bits(x):016x}" for x in xs)
        rows.append(f"    (&[{ins}], 0x{bits(canonical_mean(xs)):016x}),")
    body = "\n".join(rows)
    text = (
        "// Generated by reports/P5-23/gen_mean_vectors.py (seed 20261021); do not edit.\n"
        "// (input bits, canonical mean bits): Fraction sum / n rounded to nearest, ties to even.\n"
        "#[rustfmt::skip]\n"
        "pub const MEAN_VECTORS: &[(&[u64], u64)] = &[\n" + body + "\n];\n"
    )
    with open(sys.argv[1], "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"{len(rows)} vectors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
