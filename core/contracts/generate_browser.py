"""JSON resource types derived exclusively from annotated authority IDL."""

from __future__ import annotations
import json
from typing import Any


def resource_types(schema: dict[str, Any]) -> str:
    def atom(typ: str) -> str:
        if typ in schema.get("json_enums", {}):
            return " | ".join(json.dumps(v) for v in schema["json_enums"][typ].values())
        if typ in schema["messages"]:
            assert schema["messages"][typ].get("resource"), typ
            return typ + "Resource"
        return {"string": "string", "double": "number", "uint32": "number"}[typ]

    lines = ["// Generated by core/contracts/generate.py; DO NOT EDIT."]
    resources = {k: v for k, v in schema["messages"].items() if v.get("resource")}
    for name, message in resources.items():
        lines.append(f"export interface {name}Resource {{")
        for field in message["fields"]:
            if field["name"] == "schema_version":
                continue
            if "json_map" in field:
                key, value = field["json_map"].split(":")
                child = {
                    f["name"]: f for f in schema["messages"][field["type"]]["fields"]
                }
                assert field.get("set") == key and child[key]["type"] == "string"
                typ = f"Record<string, {atom(child[value]['type'])}>"
            else:
                typ = atom(field["type"])
                if field["repeated"]:
                    typ = f"Array<{typ}>"
            key = field.get("json_name", field["name"])
            lines.append(f"  {key}: {typ};")
        lines.append("}")
    lines.append("export interface ResourceMessageMap {")
    lines.extend(f"  {name}: {name}Resource;" for name in resources)
    lines.append("}")
    return "\n".join(lines) + "\n"
